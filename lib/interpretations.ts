export function remedyElementFor(r: SajuResult): Element {
  if (r.missing.length > 0) {
    // 결핍이 여러 개면 일간을 생해주는 오행(인성) 우선
    const helper = generatedBy(r.dayMaster.element);
    if (r.missing.includes(helper)) return helper;
    return r.missing[0];
  }
  return r.weakest;
}

