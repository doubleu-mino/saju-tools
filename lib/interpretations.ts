export function currentDaeun(r: SajuResult) {
  const nowYear = new Date().getFullYear();
  const age = nowYear - r.solar.year + 1; // 한국 나이 기준 대략
  return r.daeun.items.find((d) => age >= d.startAge && age <= d.endAge) ?? null;
}

export function buildThemeReport(r: SajuResult): ThemeReport {
  const theme: ThemeKey = r.input.theme;
  const remedyEl = remedyElementFor(r);
  const remedy = REMEDIES[remedyEl];
  const remedyReason = r.missing.includes(remedyEl)
    ? `원국에 ${remedyEl}(${ELEMENT_HANJA[remedyEl]}) 기운이 비어 있어 이를 채우는 처방입니다.`
    : `원국에서 가장 약한 ${remedyEl}(${ELEMENT_HANJA[remedyEl]}) 기운을 보강하는 처방입니다.`;

  const counts = r.tenGodCounts;
  const balance = Math.min(...r.elements.map((e) => e.count)) > 0 ? 1 : 0;

  switch (theme) {
    case "wealth": {
      const score = Math.max(1, Math.min(5, 2 + Math.min(counts.재성, 2) + (counts.식상 > 0 ? 1 : 0) - (counts.비겁 >= 3 ? 1 : 0) + balance));
      return {
        title: "재물·사업운 심층 리포트",
        summary: counts.재성 >= 3 ? "재물의 기회가 많은 재다(財多) 구조 — 그릇 관리가 곧 부(富)의 크기입니다." : counts.재성 === 0 ? "실력이 먼저, 재물은 뒤따르는 후발형 재물운입니다." : "꾸준히 쌓아 올리는 정석 재물운 — 계획과 저축이 복리로 돌아옵니다.",
        sections: wealthReport(r), remedy, remedyReason, score,
      };
    }
    case "career": {
      const score = Math.max(1, Math.min(5, 2 + Math.min(counts.관성, 2) + (counts.인성 > 0 ? 1 : 0) - (counts.식상 >= 3 ? 1 : 0) + balance));
      return {
        title: "직장·이직운 심층 리포트",
        summary: counts.관성 === 0 ? "자율성이 생명 — 틀 밖에서 더 크게 성장하는 커리어입니다." : counts.관성 >= 3 ? "중책과 명예가 따르는 구조 — 압박을 다스리는 힘이 승부처입니다." : "정공법이 통하는 안정적 조직운 — 책임의 크기가 곧 성장의 크기입니다.",
        sections: careerReport(r), remedy, remedyReason, score,
      };
    }
    case "love": {
      const sp = r.input.gender === "male" ? counts.재성 : counts.관성;
      const score = Math.max(1, Math.min(5, 2 + Math.min(sp, 2) + balance + (r.strength.label === "중화" ? 1 : 0)));
      return {
        title: "연애·결혼운 심층 리포트",
        summary: sp === 0 ? "운의 흐름을 타고 찾아오는 인연 — 나를 가꾸는 시간이 곧 준비입니다." : sp >= 3 ? "매력과 인연이 많은 구조 — 선택의 기준을 세우는 것이 사랑의 완성입니다." : "한 사람과 깊어지는 정통 연애운 — 신뢰가 쌓일수록 단단해집니다.",
        sections: loveReport(r), remedy, remedyReason, score,
      };
    }
    default: {
      const score = Math.max(1, Math.min(5, 3 + balance + (r.strength.label === "중화" ? 1 : 0)));
      return {
        title: "인생총운·대운 심층 리포트",
        summary: `${r.strength.label}의 ${r.dayMaster.title} — ${remedyEl}(${ELEMENT_HANJA[remedyEl]})의 기운을 따라 흐를 때 인생의 물길이 열립니다.`,
        sections: lifeReport(r), remedy, remedyReason, score,
      };
    }
  }
}

